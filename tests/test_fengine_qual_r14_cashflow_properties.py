ROOT=Path(__file__).resolve().parents[1]
SEED_CFO=0xCF014505
SEED_FINANCE=0xFCF11406
CASES=72
EPS=Decimal("1e-26")


def D(x):
    return Decimal(str(x))


def near(test,actual,expected,where):
    test.assertLessEqual(abs(D(actual)-D(expected)),EPS,
        f"QUAL_R14_CASHFLOW_MISMATCH {where}: actual={actual}, expected={expected}")


def make_posted_case(rng):
    receipt=D(rng.randrange(250,2000))
    supplier=D(rng.randrange(1,250))
    capex=D(rng.randrange(1,190))
    draw=D(rng.randrange(1,200))
    transfer=D(rng.randrange(1,500))
    rows=[
        {"postingId":"P1","postingDate":"2026-12-20",
         "amount":str(receipt),"direction":"IN",
         "classificationCode":"CLIENT_RECEIPT","transferId":None},
        {"postingId":"P2","postingDate":"2026-12-20",
         "amount":str(supplier),"direction":"OUT",
         "classificationCode":"SUPPLIER_PAYMENT","transferId":None},
        {"postingId":"P3","postingDate":"2026-12-20",
         "amount":str(capex),"direction":"OUT",
         "classificationCode":"CAPEX_PAYMENT","transferId":None},
        {"postingId":"P4","postingDate":"2026-12-20",
         "amount":str(draw),"direction":"IN",
         "classificationCode":"LOAN_DRAW","transferId":None},
        {"postingId":"P5","postingDate":"2026-12-20",
         "amount":str(transfer),"direction":"OUT",
         "classificationCode":"TRANSFER_INTERNAL","transferId":"T-1"},
        {"postingId":"P6","postingDate":"2026-12-20",
         "amount":str(transfer),"direction":"IN",
         "classificationCode":"TRANSFER_INTERNAL","transferId":"T-1"},
    ]
    net=receipt-supplier-capex+draw
    l=ledger(postings=rows,closing=str(1000+net))
    return l,rows,receipt,supplier,capex,draw,net


class QualR14CashflowProperties(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.engine=ReferenceEngine(ROOT)

    def calc(self,model,variant,inputs,config):
        return self.engine.calculate(
            model,variant,inputs,config,reference_mode=True
        ).output

    @independent_decimal_precision
    def test_144_direct_posted_and_reclassified_cfo_cash_conservation(self):
        rng=random.Random(SEED_CFO)
        count=0
        for index in range(CASES):
            src,rows,receipt,supplier,capex,draw,net=make_posted_case(rng)
            changed=copy.deepcopy(src)
            changes=[{"postingId":"P3",
                      "newClassificationCode":"SUPPLIER_PAYMENT",
                      "reasonCode":"DOCUMENTED_RECLASSIFICATION"}]
            changed["reclassificationOverrides"]=changes
            changed["reclassificationRevisionSha256"]=override_revision_sha256(
                src["sourceRevisionSha256"],changes
            )
            for variant,input_data,operating,invest in (
                ("DIRECT_POSTED_CFO",src,receipt-supplier,-capex),
                ("DIRECT_RECLASSIFIED_CFO",changed,receipt-supplier-capex,D(0)),
            ):
                with self.subTest(seed=SEED_CFO,index=index,variant=variant):
                    out=self.calc(
                        "HC.CASH.04",variant,input_data,configuration()
                    )
                    near(self,out["cashFlowFromOperations"],operating,"CFO")
                    near(self,out["operatingReceipts"],receipt,"receipts")
                    near(self,out["netInvestingCashFlow"],invest,"investing")
                    near(self,out["netFinancingCashFlow"],draw,"financing")
                    near(self,out["netAllCashFlow"],net,"net all")
                    near(self,out["closingCash"],1000+net,"closing")
                    near(self,D(out["cashFlowFromOperations"])
                         +D(out["netInvestingCashFlow"])
                         +D(out["netFinancingCashFlow"]),net,"cross-class conservation")
                    near(self,D(out["openingCash"])+D(out["netAllCashFlow"]),
                         out["closingCash"],"cash identity")
                    self.assertEqual(out["excludedTransferPostingCount"],2)
                    count+=1
        self.assertEqual(count,2*CASES)

    @independent_decimal_precision
    def test_288_indirect_cfo_fcff_and_two_fcfe_variants_valuation(self):
        rng=random.Random(SEED_FINANCE)
        count=0
        for index in range(CASES):
            ni=D(rng.randrange(-1000,2000))/10
            noncash=D(rng.randrange(0,500))/10
            nwc=D(rng.randrange(-800,800))/10
            capex=D(rng.randrange(0,1200))/10
            draw=D(rng.randrange(0,1200))/10
            repay=D(rng.randrange(0,1200))/10
            rate=D(rng.randrange(1,300))/1000
            period=rng.randrange(1,8)
            cfo=ni+noncash-nwc
            indirect={**cfo_inputs(),
                      "netIncome":str(ni),
                      "noncashAdjustments":[{"code":"NONCASH",
                                            "amount":str(noncash)}],
                      "deltaOperatingNwc":str(nwc)}
            out=self.calc(
                "HC.CASH.05","INDIRECT_CFO_ADJUSTMENT",
                indirect,cfo_config()
            )
            near(self,out["cashFlowFromOperations"],cfo,"indirect CFO")
            near(self,out["workingCapitalCashEffect"],-nwc,
                 "NWC signed cash effect")
            count+=1
            ebit=D(rng.randrange(0,2000))/10
            tax=D(rng.randrange(0,1000))/1000
            plant={**fcff_inputs(),"ebit":str(ebit),"taxRate":str(tax),
                   "noncashOperatingCharges":str(noncash),
                   "cashCapex":str(capex),"deltaOperatingNwc":str(nwc)}
            unlevered=self.calc(
                "HC.DCF.05","FCFF_UNLEVERED",plant,fcff_config()
            )
            near(self,unlevered["freeCashFlowToFirm"],
                 ebit*(1-tax)+noncash-capex-nwc,"FCFF independent")
            count+=1
            results={}
            for variant in ("FCFE_LEVERED","FCFE_NORMALIZED"):
                inp,cfg=fcfe_fixture(
                    variant,cfo=str(cfo),income=str(ni),
                    noncash=str(noncash),nwc=str(nwc),
                    capex=str(capex),draw=str(draw),repay=str(repay),
                    rate=str(rate),period=period
                )
                out=self.calc("HC.DCF.06",variant,inp,cfg)
                with localcontext() as ctx:
                    ctx.prec=70
                    cash=cfo-capex+draw-repay
                    discounted=cash/(1+rate)**period
                near(self,out["operatingCashFlowAfterInterest"],cfo,
                     f"{variant} CFO")
                near(self,out["netBorrowing"],draw-repay,
                     f"{variant} net debt")
                near(self,out["freeCashFlowToEquity"],cash,
                     f"{variant} total equity cash")
                near(self,out["presentValueOfFcfe"],discounted,
                     f"{variant} discounted cash")
                results[variant]=out
                count+=1
            self.assertEqual(
                reconcile_fcfe_methods(
                    results["FCFE_LEVERED"],results["FCFE_NORMALIZED"]
                )["status"],"MATCHED_REFERENCE_NOT_S2",
            )
        self.assertEqual(count,4*CASES)

    @independent_decimal_precision
    def test_source_identity_swap_and_cash_balance_forgery_fail_closed(self):
        src,rows,_,_,_,_,_=make_posted_case(random.Random(SEED_CFO))
        config=configuration()
        attacks=[]
        modified=copy.deepcopy(src)
        modified["postings"][0]["amount"]="99999"
        attacks.append((modified,config,"DIRECT_CFO_SOURCE_DIGEST_MISMATCH"))
        forged=copy.deepcopy(src)
        forged["closingCash"]=str(D(src["closingCash"])+1)
        forged["sourceRevisionSha256"]=posted_source_sha256({
            key:forged[key] for key in (
                "periodStart","periodEnd","currency",
                "openingCash","closingCash","postings"
            )
        })
        attacks.append((forged,config,"DIRECT_CFO_CASH_BALANCE_MISMATCH"))
        attacks.append((src,{**config,"cashClassification":"f"*64},
                        "DIRECT_CFO_CLASSIFICATION_SHA_MISMATCH"))
        attacks.append((src,{**config,"periodCutoff":"2027-01-01"},
                        "DIRECT_CFO_PERIOD_CUTOFF_MISMATCH"))
        for inp,cfg,expected in attacks:
            with self.subTest(expected=expected):
                with self.assertRaises(CalculationError) as exc:
                    self.calc("HC.CASH.04","DIRECT_POSTED_CFO",inp,cfg)
                self.assertEqual(exc.exception.code,expected)

    @independent_decimal_precision
    def test_fcfe_two_methods_context_conflict_and_reconciliation_mismatch(self):
        levered,config=fcfe_fixture("FCFE_LEVERED",cfo="100")
        normalized,nconfig=fcfe_fixture(
            "FCFE_NORMALIZED",income="90",noncash="30",nwc="20"
        )
        a=self.calc("HC.DCF.06","FCFE_LEVERED",levered,config)
        b=self.calc("HC.DCF.06","FCFE_NORMALIZED",normalized,nconfig)
        self.assertEqual(reconcile_fcfe_methods(a,b)["difference"],"0")
        changed,_=fcfe_fixture("FCFE_NORMALIZED",income="91",
                               noncash="30",nwc="20")
        b_bad=self.calc("HC.DCF.06","FCFE_NORMALIZED",changed,nconfig)
        with self.assertRaises(CalculationError) as exc:
            reconcile_fcfe_methods(a,b_bad)
        self.assertEqual(exc.exception.code,"FCFE_RECONCILIATION_MISMATCH")

